begin;
do $test$
declare
  a uuid:=gen_random_uuid(); staff uuid:=gen_random_uuid(); parent uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid();
  district uuid:=gen_random_uuid(); school uuid:=gen_random_uuid(); other_school uuid:=gen_random_uuid(); year_id uuid:=gen_random_uuid();
  student uuid:=gen_random_uuid(); other_student uuid:=gen_random_uuid(); device uuid:=gen_random_uuid(); event uuid:=gen_random_uuid();
  request uuid:=gen_random_uuid(); observed timestamptz:=clock_timestamp(); badge jsonb; replacement jsonb; result jsonb; totals jsonb;
  v_user uuid; n integer; checks jsonb:='[]'::jsonb;
begin
  foreach v_user in array array[a,staff,parent,outsider] loop
    insert into auth.users(id,email,aud,role,is_anonymous) values(v_user,'scan-fixture-'||v_user||'@example.invalid','authenticated','authenticated',false);
    insert into public.turc_accounts(user_id,display_name) values(v_user,'Fictional scanner tester');
  end loop;
  insert into public.turc_districts(id,name) values(district,'Fictional scanning district');
  insert into public.turc_schools(id,district_id,name,timezone) values(school,district,'Fictional scanning school','America/Los_Angeles'),(other_school,district,'Isolated scanning school','America/Los_Angeles');
  insert into public.turc_school_years(id,school_id,label,starts_on,ends_on,active) values(year_id,school,'Test year',current_date-100,current_date+100,true);
  insert into public.turc_students(id,school_id,external_student_id,first_name,last_name) values(student,school,'0001','Maya','Fictional'),(other_student,school,'0002','Oliver','Fictional');
  insert into public.turc_enrollments(school_id,student_id,school_year_id) values(school,student,year_id),(school,other_student,year_id);
  insert into public.turc_memberships(user_id,district_id,school_id,role) values(a,district,school,'admin'),(staff,district,school,'staff'),(parent,district,school,'parent');
  insert into public.turc_guardian_links(guardian_user_id,school_id,student_id) values(parent,school,student);
  perform set_config('request.jwt.claim.sub',a::text,true);
  execute 'set local role authenticated';
  result:=public.turc_scan_course(school);
  if result->>'configured'<>'false' then raise exception 'Invented course';end if;
  checks:=checks||'["No course is invented"]';
  result:=public.turc_scan_course(school,'Measured loop',100000,30);
  if (result->>'distance_mm')::bigint<>100000 then raise exception 'Course not persisted';end if;
  checks:=checks||'["Admin course configuration"]';
  if public.turc_badge_assignment(student) is not null then raise exception 'Badge existed before UID assignment';end if;
  checks:=checks||'["No QR credential before UID assignment"]';
  badge:=public.turc_assign_tag(student,'04112233445566',request);
  if badge->>'token' !~ '^turc:v1:[a-f0-9]{64}$' then raise exception 'Malformed badge';end if;
  checks:=checks||'["Opaque badge credential"]';
  result:=public.turc_badge_assignment(student);
  if result->>'id'<>badge->>'id' then raise exception 'Viewing badge replaced it';end if;
  checks:=checks||'["Viewing badge keeps existing credential"]';
  if badge->>'tag_uid'<>'04112233445566' or badge->>'student_number'<>'0001' then raise exception 'UID or printable student identity missing';end if;
  checks:=checks||'["UID assignment supplies printable student information"]';
  result:=public.turc_assign_tag(student,'04112233445566',request);
  if result->>'id'<>badge->>'id' then raise exception 'UID request retry duplicated assignment';end if;
  checks:=checks||'["Assignment retry is idempotent"]';
  begin perform public.turc_assign_tag(other_student,'04112233445566',gen_random_uuid());raise exception 'Sticker was assigned twice';exception when unique_violation then checks:=checks||'["Assigned UID cannot be stolen by a second student"]';end;
  begin perform public.turc_runner_badge(student,false,gen_random_uuid());raise exception 'QR-first endpoint remained enabled';exception when insufficient_privilege then checks:=checks||'["Previous QR-first endpoint retired"]';end;
  result:=public.turc_submit_scan(school,badge->>'token',event,device,'qr',observed);
  if result->>'accepted'<>'true' or (result#>>'{totals,today_laps}')::integer<>1 then raise exception 'First lap rejected: %',result;end if;
  checks:=checks||'["QR scan creates first lap and totals"]';
  result:=public.turc_submit_scan(school,badge->>'token',event,device,'qr',observed);
  if result->>'replayed'<>'true' then raise exception 'Retry was not idempotent';end if;
  checks:=checks||'["Retry returns original result"]';
  begin perform public.turc_submit_scan(school,badge->>'token',event,device,'nfc',observed);raise exception 'Changed event payload allowed';exception when invalid_parameter_value then checks:=checks||'["Changed replay payload rejected"]';end;
  result:=public.turc_submit_scan(school,badge->>'tag_uid',gen_random_uuid(),gen_random_uuid(),'nfc',clock_timestamp());
  if result->>'reason'<>'cooldown' then raise exception 'Cross-device cooldown bypassed';end if;
  checks:=checks||'["QR and NFC share cooldown across devices"]';
  execute 'reset role';
  select count(*) into n from turc_private.turc_days where school_id=school;
  if n<>1 then raise exception 'Daily session duplicated';end if;
  checks:=checks||'["First accepted lap creates one daily session"]';
  perform set_config('request.jwt.claim.sub',staff::text,true);execute 'set local role authenticated';
  begin perform public.turc_scan_course(school,'Tampered',1,0);raise exception 'Staff changed course';exception when insufficient_privilege then checks:=checks||'["Staff cannot change course"]';end;
  begin perform public.turc_assign_tag(student,'04aabbccddeeff',gen_random_uuid());raise exception 'Staff issued badge';exception when insufficient_privilege then checks:=checks||'["Staff cannot issue badge"]';end;
  begin perform public.turc_confirm_nfc((badge->>'id')::uuid);raise exception 'Staff confirmed badge';exception when insufficient_privilege then checks:=checks||'["Previous NDEF confirmation endpoint retired"]';end;
  begin update public.turc_laps set distance_mm=1 where student_id=student;raise exception 'Client edited laps';exception when insufficient_privilege then checks:=checks||'["Client cannot forge lap records"]';end;
  begin perform public.turc_submit_scan(other_school,badge->>'token',gen_random_uuid(),device,'qr',clock_timestamp());raise exception 'Cross-school scan allowed';exception when insufficient_privilege then checks:=checks||'["Cross-school operator denied"]';end;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',a::text,true);execute 'set local role authenticated';
  replacement:=public.turc_assign_tag(student,'04aabbccddeeff',gen_random_uuid());
  if replacement->>'token'=badge->>'token' then raise exception 'Replacement reused token';end if;
  checks:=checks||'["Replacement rotates token"]';
  result:=public.turc_submit_scan(school,badge->>'token',gen_random_uuid(),device,'qr',clock_timestamp());
  if result->>'reason'<>'unknown_or_replaced_badge' then raise exception 'Revoked badge worked';end if;
  checks:=checks||'["Old QR credential revoked"]';
  result:=public.turc_submit_scan(school,badge->>'tag_uid',gen_random_uuid(),device,'nfc',clock_timestamp());
  if result->>'reason'<>'unknown_or_replaced_badge' then raise exception 'Previous UID still mapped';end if;
  checks:=checks||'["Old sticker UID revoked on replacement"]';
  if replacement->>'tag_uid'<>'04AABBCCDDEEFF' then raise exception 'UID case was not normalized';end if;
  checks:=checks||'["Factory UID canonicalization"]';
  result:=public.turc_scan_course(school,'Updated measured loop',200000,0);
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',staff::text,true);execute 'set local role authenticated';
  result:=public.turc_submit_scan(school,replacement->>'tag_uid',gen_random_uuid(),device,'nfc',clock_timestamp());
  if result->>'accepted'<>'true' then raise exception 'Staff NFC scan rejected: %',result;end if;
  checks:=checks||'["Staff NFC scan accepted"]';
  totals:=public.turc_runner_totals(student);
  if (totals->>'today_mm')::bigint<>300000 or (totals->>'today_laps')::integer<>2 or (totals->>'lifetime_mm')::bigint<>300000 then raise exception 'Historical distance changed: %',totals;end if;
  checks:=checks||'["Captured distance survives course changes"]';
  result:=public.turc_submit_scan(school,replacement->>'token',gen_random_uuid(),device,'qr',clock_timestamp()-interval '5 minutes');
  if result->>'reason'<>'clock_or_connection' then raise exception 'Stale offline timestamp accepted';end if;
  checks:=checks||'["Stale offline scans do not silently count"]';
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',parent::text,true);execute 'set local role authenticated';
  totals:=public.turc_runner_totals(student);
  if (totals->>'today_laps')::integer<>2 then raise exception 'Parent linked totals unavailable';end if;
  checks:=checks||'["Parent sees linked runner totals"]';
  begin perform public.turc_runner_totals(other_student);raise exception 'Parent read unlinked runner';exception when insufficient_privilege then checks:=checks||'["Parent cannot read unlinked totals"]';end;
  begin perform public.turc_submit_scan(school,replacement->>'token',gen_random_uuid(),device,'qr',clock_timestamp());raise exception 'Parent scanned';exception when insufficient_privilege then checks:=checks||'["Parent cannot submit scans"]';end;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',outsider::text,true);execute 'set local role authenticated';
  select count(*) into n from public.turc_laps where school_id=school;
  if n<>0 then raise exception 'Outsider read laps';end if;
  checks:=checks||'["Lap table RLS isolates outsider"]';
  execute 'reset role';
  update public.turc_memberships set active=false where user_id=staff;
  perform set_config('request.jwt.claim.sub',staff::text,true);execute 'set local role authenticated';
  begin perform public.turc_submit_scan(school,replacement->>'tag_uid',gen_random_uuid(),device,'nfc',clock_timestamp());raise exception 'Revoked staff scanned';exception when insufficient_privilege then checks:=checks||'["Membership revocation immediately blocks scanning"]';end;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub','',true);execute 'set local role anon';
  begin perform public.turc_scan_course(school);raise exception 'Anon read course';exception when insufficient_privilege then checks:=checks||'["Anon has no scanning RPC access"]';end;
  execute 'reset role';
  perform set_config('turc.test_results',checks::text,true);
end;
$test$;
select jsonb_array_length(current_setting('turc.test_results')::jsonb) as passed_count,current_setting('turc.test_results')::jsonb as checks;
